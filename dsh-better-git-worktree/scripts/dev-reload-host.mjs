// Development convenience: give the Host half a fresh module URL after an edit.
//
// Node caches ES modules by resolved URL and the loader imports a row's module
// once per process, so a host-side edit is otherwise invisible until the dsh
// service restarts. This script:
//
//   1. writes plugins/dsh-better-git-worktree/entry-r<N+1>.mjs, whose re-export
//      carries a new query so host-main.mjs is evaluated again;
//   2. versions host-main.mjs's `./host/*.mjs` imports with the same revision
//      (node caches modules by URL), and
//   3. repoints the profile patch row (`./plugins/dsh-better-git-worktree/
//      entry-rN.mjs`) at it.
//
// The row id and the package directory stay the same, so the Client half keeps
// resolving to the same package (`dsh-better-git-worktree`) — only the Host
// module URL changes. Do not use this in a deployment that can simply restart.
//
// Usage: node scripts/dev-reload-host.mjs [--profile <path-to-cordis.patch.yml>]

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const pluginDir = join(here, '..');

const args = process.argv.slice(2);
const profileIndex = args.indexOf('--profile');
const patchPath =
  profileIndex >= 0 && args[profileIndex + 1] !== undefined
    ? args[profileIndex + 1]
    : join(here, '..', '..', '..', 'cordis.patch.yml');

const patch = readFileSync(patchPath, 'utf8');
const match = patch.match(/name: \.\/plugins\/dsh-better-git-worktree\/entry-r(\d+)\.mjs/);
const current = match === null ? -1 : Number(match[1]);
const next = current + 1;

const entryName = `entry-r${next}.mjs`;
writeFileSync(
  join(pluginDir, entryName),
  `// dsh-better-git-worktree — versioned Host entry (development reload lever).\n`
    + `// Generated by scripts/dev-reload-host.mjs - see the plugin README.\n`
    + `export { default, inject, name } from './host-main.mjs?r=${next}';\n`,
  'utf8',
);

// Version the host modules too: node caches ES modules by URL, and a plugin row
// is imported per process, so a plain `./host/x.mjs` import would keep serving
// the copy loaded at the previous revision. Static imports (unlike a dynamic
// import inside a plugin module) are fine here.
const mainPath = join(pluginDir, 'host-main.mjs');
const main = readFileSync(mainPath, 'utf8');
const versioned = main.replace(/(from '\.\/host\/[a-z-]+\.mjs)(\?r=\d+)?'/g, `$1?r=${next}'`);
if (versioned !== main) writeFileSync(mainPath, versioned, 'utf8');

const nextPatch = match === null
  ? patch.replace(
      /(- id: better-git-worktree\n\s+name: )\S+/,
      `$1./plugins/dsh-better-git-worktree/${entryName}`,
    )
  : patch.replace(
      /name: \.\/plugins\/dsh-better-git-worktree\/entry-r\d+\.mjs/,
      `name: ./plugins/dsh-better-git-worktree/${entryName}`,
    );
if (nextPatch === patch) throw new Error(`could not find the better-git-worktree row in ${patchPath}`);
writeFileSync(patchPath, nextPatch, 'utf8');
console.log(`host entry → ${entryName} (patch row repointed; the watcher reloads it live)`);
